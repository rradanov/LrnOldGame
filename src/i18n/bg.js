/** Българска форма за число: 1 → единствено, иначе множествено (бройна форма) — plural(2, 'ден', 'дни') → 'дни'. */
export const plural = (n, one, many) => (Math.abs(Number(n)) === 1 ? one : many);

/** Число с десетична запетая (bg-BG): num(1.5, 2) → '1,50'. */
export const decimal = (x, digits) => x.toLocaleString('bg-BG', { minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false });

/**
 * Прост шаблон: fmt('от {min}', {min: 1}) → 'от 1'.
 * Форма за число: '{n} {n|ден|дни}' → '1 ден' / '2 дни' (D3).
 */
export function fmt(str, vars = {}) {
  return str
    .replace(/\{(\w+)\|([^|{}]*)\|([^|{}]*)\}/g, (m, k, one, many) => (k in vars ? plural(vars[k], one, many) : m))
    .replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
