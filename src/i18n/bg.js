/** Прост шаблон: fmt('от {min}', {min: 1}) → 'от 1'. */
export function fmt(str, vars = {}) {
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
